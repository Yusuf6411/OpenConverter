#!/usr/bin/env python3
"""Regenerates crates/oc-vp8/src/tables.rs from the constant tables of a libwebp shared object.

These are the numeric tables of the VP8 specification (RFC 6386): quantizer lookup, token
probabilities and the key-frame sub-block mode probabilities. They are read once, here, at
development time; nothing at runtime depends on libwebp.

Usage: gen_tables.py /usr/lib/x86_64-linux-gnu/libwebp.so.7.1.8 > crates/oc-vp8/src/tables.rs
The offsets are for libwebp 1.6.0 (Debian/Ubuntu libwebp7 1.6.0); each table is checked
against its known first/last values before output.
"""
import struct
import sys

d = open(sys.argv[1], "rb").read()

def u8(off, n):
    return list(d[off:off + n])

def u16(off, n):
    return list(struct.unpack("<%dH" % n, d[off:off + 2 * n]))

dc = u8(420928, 128)
ac = u16(420672, 128)
zig = u8(420656, 16)
bands = u8(421056, 16)
default = u8(421088, 1056)
update = u8(422144, 1056)
bmodes = u8(423264, 900)
assert dc[:4] == [4, 5, 6, 7] and dc[-1] == 157
assert ac[:4] == [4, 5, 6, 7] and ac[-1] == 284
assert zig == [0, 1, 4, 8, 5, 2, 3, 6, 9, 12, 13, 10, 7, 11, 14, 15]
assert bands == [0, 1, 2, 3, 6, 4, 5, 6, 6, 6, 6, 6, 6, 6, 6, 7]
assert default == u8(421088, 1056) and default[0] == 128
assert update[33:36] == [176, 246, 255]
assert bmodes[:6] == [231, 120, 48, 89, 115, 113]
assert d[454528:454528 + 900] == bytes(bmodes)


def fmt(name, ty, vals, per_line=16, indent=""):
    out = ["pub const %s: %s = [" % (name, ty)]
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    out.append("];")
    return "\n".join(out)


def nest(name, vals, dims, ty="u8"):
    def rec(v, dims, depth):
        if len(dims) == 1:
            return "[" + ", ".join(str(x) for x in v) + "]"
        step = len(v) // dims[0]
        inner = [rec(v[i * step:(i + 1) * step], dims[1:], depth + 1) for i in range(dims[0])]
        pad = "    " * (depth + 1)
        return "[\n" + "".join(pad + s + ",\n" for s in inner) + "    " * depth + "]"
    t = ty
    for n in reversed(dims):
        t = "[%s; %d]" % (t, n)
    return "pub const %s: %s = %s;" % (name, t, rec(vals, dims, 0))


print("//! Constant tables of the VP8 specification (RFC 6386). Generated by tools/gen_tables.py;")
print("//! do not edit by hand.")
print()
print("/// Quantizer step by index for DC coefficients.")
print(fmt("DC_TABLE", "[u8; 128]", dc, 16))
print()
print("/// Quantizer step by index for AC coefficients.")
print(fmt("AC_TABLE", "[u16; 128]", ac, 16))
print()
print("/// Zigzag scan order of a 4x4 block.")
print(fmt("ZIGZAG", "[u8; 16]", zig))
print()
print("/// Coefficient position to probability band; the 17th entry serves the end of the block.")
print(fmt("BANDS", "[u8; 17]", bands + [0]))
print()
print("/// Default token probabilities, indexed [block type][band][context][node].")
print(nest("COEFF_PROBS", default, [4, 8, 3, 11]))
print()
print("/// Probabilities that a key frame updates a token probability.")
print(nest("COEFF_UPDATE_PROBS", update, [4, 8, 3, 11]))
print()
print("/// Key-frame sub-block mode probabilities, indexed [above mode][left mode][tree node].")
print(nest("BMODE_PROBS", bmodes, [10, 10, 9]))
