"""Writes src/bc6h_layout.rs: the order in which the bits of a BC6H block fill the
endpoint fields, one list per mode, as (component, endpoint, bit count, shift).

Dev-time only. The bit order is read from the switch statement in the BC6H decoder of
texture2ddecoder (a reference used for the layout and nothing else):

    python3 tools/gen_bc6h_layout.py path/to/bcn.cpp
"""
import re
import sys

src = open(sys.argv[1]).read()
start = src.index("static void decode_bc6_block")
end = src.index("const Bc6hModeInfo mi", start)
body = src[start:end]

modes = {}
for m in re.finditer(r"case (\d+):\n(.*?)break;", body, re.S):
    mode = int(m.group(1))
    fields = []
    for f in re.finditer(r"ep([RGB])\[(\d)\] \|= bit\.read\((\d+)\) << (\d+);", m.group(2)):
        fields.append(("RGB".index(f.group(1)), int(f.group(2)), int(f.group(3)), int(f.group(4))))
    modes[mode] = fields

lines = [
    "// Generated by tools/gen_bc6h_layout.py; do not edit.",
    "// For each mode (its 2 or 5 bit selector) the endpoint fields in the order their bits",
    "// appear after the selector: (component, endpoint, bit count, shift).",
    "/// One endpoint field: component, endpoint, bit count, shift.",
    "pub type Field = (u8, u8, u8, u8);",
    "pub const LAYOUT: [(u8, &[Field]); %d] = [" % len(modes),
]
for mode in sorted(modes):
    items = ", ".join("(%d, %d, %d, %d)" % f for f in modes[mode])
    lines.append("    (%d, &[%s])," % (mode, items))
lines.append("];")
open("src/bc6h_layout.rs", "w").write("\n".join(lines) + "\n")
print(sorted(modes))
