"""Derives the BC7 partition and anchor tables by decoding probe blocks with Pillow.

BC7 (Direct3D 11) stores 64 two-subset and 64 three-subset partition shapes plus the "anchor"
pixel of each subset, whose index has one bit less. The shapes are constants of the format;
rather than copying them from a document, each one is read back from an independent decoder:
a probe block gives every subset a different flat colour, so the decoded pixels show the
subset of each pixel, and an index field of all ones shows the anchors (their index is one bit
short, so they decode darker). Writes `src/bc7_tables.rs`. Dev-time only, needs Pillow.
"""
import io
import os
import struct
from PIL import Image


def dds_with_blocks(blocks):
    n = len(blocks)
    w, h = 4 * n, 4
    hdr = b"DDS " + struct.pack("<7I", 124, 0x1007 | 0x80000, h, w, 16 * n, 0, 1)
    hdr += b"\0" * 44
    hdr += struct.pack("<8I", 32, 4, int.from_bytes(b"DX10", "little"), 0, 0, 0, 0, 0)
    hdr += struct.pack("<5I", 0x1000, 0, 0, 0, 0)
    dx10 = struct.pack("<5I", 98, 3, 0, 1, 0)
    return hdr + dx10 + b"".join(blocks)


def decode(blocks):
    im = Image.open(io.BytesIO(dds_with_blocks(blocks))).convert("RGBA")
    out = []
    for i in range(len(blocks)):
        out.append([im.getpixel((4 * i + (p % 4), p // 4)) for p in range(16)])
    return out


class Bits:
    def __init__(self):
        self.v = 0
        self.n = 0

    def put(self, value, bits):
        self.v |= (value & ((1 << bits) - 1)) << self.n
        self.n += bits

    def block(self):
        assert self.n == 128, self.n
        return self.v.to_bytes(16, "little")


def mode1_probe(partition, anchors):
    """Two subsets. Flat colours 0 and max, or (anchors) ramps 0..max with every index bit set."""
    b = Bits()
    b.put(0b10, 2)  # mode 1
    b.put(partition, 6)
    ends = (0, 63, 0, 63) if anchors else (0, 0, 63, 63)
    for _ in range(3):  # R, G, B: four 6-bit endpoints each (s0e0 s0e1 s1e0 s1e1)
        for v in ends:
            b.put(v, 6)
    b.put(0, 1)  # shared p-bits: subset 0 ends at 126 -> 0, subset 1 at 127 -> 255
    b.put(1, 1)
    b.put((1 << 46) - 1 if anchors else 0, 46)
    return b.block()


def mode2_probe(partition, anchors):
    """Three subsets, 5-bit endpoints, 2-bit indices."""
    b = Bits()
    b.put(0b100, 3)  # mode 2
    b.put(partition, 6)
    ends = (0, 31, 0, 31, 0, 31) if anchors else (0, 0, 31, 31, 15, 15)
    for _ in range(3):
        for v in ends:
            b.put(v, 5)
    b.put((1 << 29) - 1 if anchors else 0, 29)
    return b.block()


def main():
    out = []
    for name, fn, subsets in (("2", mode1_probe, 2), ("3", mode2_probe, 3)):
        flat = decode([fn(p, False) for p in range(64)])
        ramp = decode([fn(p, True) for p in range(64)])
        shapes, anchors = [], []
        levels = sorted({px[0] for blk in flat for px in blk})
        # Flat colours: 0, then the middle value (3 subsets only), then 255.
        order = {0: 0, 255: 1} if subsets == 2 else {0: 0, 255: 1}
        if subsets == 3:
            mid = [v for v in levels if v not in (0, 255)]
            assert len(mid) == 1, levels
            order[mid[0]] = 2
        for f, r in zip(flat, ramp):
            shape = [order[px[0]] for px in f]
            shapes.append(shape)
            # Anchor of each subset k >= 1: the pixel of that subset whose ramp value is not the maximum.
            anc = []
            for k in range(1, subsets):
                cand = [i for i in range(16) if shape[i] == k and r[i][0] < max(px[0] for px in r if True)]
                anc.append(cand)
            anchors.append(anc)
        out.append((name, shapes, anchors, subsets))
    text = ["// Generated by tools/gen_bc7_tables.py from Pillow's BC7 decoder; do not edit.\n"]
    for name, shapes, anchors, subsets in out:
        text.append(f"pub const PARTITION{name}: [[u8; 16]; 64] = [\n")
        for sh in shapes:
            text.append("    [" + ", ".join(str(v) for v in sh) + "],\n")
        text.append("];\n")
        for k in range(1, subsets):
            vals = []
            for a in anchors:
                cand = a[k - 1]
                assert len(cand) == 1, (name, k, cand)
                vals.append(cand[0])
            suffix = "" if subsets == 2 else f"_{k}"
            text.append(f"pub const ANCHOR{name}{suffix}: [u8; 64] = [" + ", ".join(map(str, vals)) + "];\n")
    path = os.path.join(os.path.dirname(__file__), "..", "src", "bc7_tables.rs")
    open(path, "w").write("".join(text))
    print("wrote", path)


if __name__ == "__main__":
    main()
