/// The kernels of an image: 15, 55 and 210 weights for the 2x, 4x and 8x steps.
#[derive(Clone, Debug)]
pub struct Kernels {
    pub up2: Vec<f32>,
    pub up4: Vec<f32>,
    pub up8: Vec<f32>,
}

impl Kernels {
    pub fn default_kernels() -> Self {
        Self { up2: DEFAULT_UP2.to_vec(), up4: DEFAULT_UP4.to_vec(), up8: DEFAULT_UP8.to_vec() }
    }
}

/// Mirror an index into `0..n` (the edge sample is repeated).
fn mirror(i: isize, n: usize) -> usize {
    let n = n as isize;
    let mut i = i;
    while i < 0 || i >= n {
        i = if i < 0 { -i - 1 } else { 2 * n - i - 1 };
    }
    i as usize
}

/// Upsample a plane by `2^log`. Returns the new plane and its size.
pub fn upsample(plane: Vec<f32>, w: usize, h: usize, log: u32, k: &Kernels) -> (Vec<f32>, usize, usize) {
    let mut cur = (plane, w, h);
    for _ in 0..log / 3 {
        cur = step::<8>(&cur.0, cur.1, cur.2, &k.up8);
    }
    match log % 3 {
        1 => step::<2>(&cur.0, cur.1, cur.2, &k.up2),
        2 => step::<4>(&cur.0, cur.1, cur.2, &k.up4),
        _ => cur,
    }
}

fn step<const K: usize>(src: &[f32], w: usize, h: usize, weights: &[f32]) -> (Vec<f32>, usize, usize) {
    let (ow, oh) = (w * K, h * K);
    let half = K / 2;
    // The weights hold the upper triangle of a symmetric (5*half) x (5*half) matrix, row by row.
    let mut quarter = vec![[0f32; 25]; half * half];
    let mut idx = 0usize;
    for y in 0..5 * half {
        for x in y..5 * half {
            let wt = weights.get(idx).copied().unwrap_or(0.0);
            idx += 1;
            quarter[(y / 5) * half + x / 5][(y % 5) * 5 + x % 5] = wt;
            quarter[(x / 5) * half + y / 5][(x % 5) * 5 + y % 5] = wt;
        }
    }
    let mut out = vec![0f32; ow * oh];
    for y in 0..oh {
        let ry = (y / K) as isize;
        let my = (y % K).min(K - y % K - 1);
        let flip_v = y % K >= half;
        for x in 0..ow {
            let rx = (x / K) as isize;
            let mx = (x % K).min(K - x % K - 1);
            let flip_h = x % K >= half;
            let kernel = &quarter[my * half + mx];
            let mut sum = 0f32;
            let (mut lo, mut hi) = (f32::INFINITY, f32::NEG_INFINITY);
            for iy in 0..5usize {
                let ky = if flip_v { 4 - iy } else { iy };
                let sy = mirror(ry + iy as isize - 2, h);
                for ix in 0..5usize {
                    let kx = if flip_h { 4 - ix } else { ix };
                    let s = src[sy * w + mirror(rx + ix as isize - 2, w)];
                    sum += kernel[ky * 5 + kx] * s;
                    lo = lo.min(s);
                    hi = hi.max(s);
                }
            }
            out[y * ow + x] = if lo.is_finite() && hi.is_finite() { sum.clamp(lo, hi) } else { f32::NAN };
        }
    }
    (out, ow, oh)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flat_input_stays_flat() {
        let k = Kernels::default_kernels();
        for log in 1..=3 {
            let (out, w, h) = upsample(vec![0.5; 6 * 5], 6, 5, log, &k);
            assert_eq!((w, h), (6 << log, 5 << log));
            assert!(out.iter().all(|&v| (v - 0.5).abs() < 1e-4), "log {log}");
        }
    }
}
