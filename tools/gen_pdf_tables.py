#!/usr/bin/env python3
"""Generates crates/oc-pdf/src/tables.rs: Adobe Glyph List and the standard PDF encodings (from fontTools)."""
from fontTools.agl import AGL2UV, UV2AGL
from fontTools.encodings.StandardEncoding import StandardEncoding
from fontTools.encodings.MacRoman import MacRoman
import codecs

def winansi():
    out = []
    for c in range(256):
        if c < 32 or c == 127:
            out.append('.notdef'); continue
        try:
            u = ord(bytes([c]).decode('cp1252'))
        except UnicodeDecodeError:
            out.append('bullet'); continue
        if c == 0xA0: out.append('space'); continue
        if c == 0xAD: out.append('hyphen'); continue
        out.append(UV2AGL.get(u, '.notdef'))
    # PDF reference differences from cp1252 + AGL preferences
    fix = {0x27: 'quotesingle', 0x60: 'grave', 0x2D: 'hyphen', 0x20: 'space', 0x95: 'bullet', 0x7F: 'bullet', 0x81: 'bullet', 0x8D: 'bullet', 0x8F: 'bullet', 0x90: 'bullet', 0x9D: 'bullet'}
    for k, v in fix.items(): out[k] = v
    return out

def main():
    agl = sorted((n, u) for n, u in AGL2UV.items() if isinstance(u, int))
    lines = ['//! Generated by tools/gen_pdf_tables.py. Do not edit.', '', 'pub static AGL: &[(&str, u32)] = &[']
    for n, u in agl:
        lines.append(f'    ("{n}", {u}),')
    lines.append('];')
    for name, enc in [('STANDARD', StandardEncoding), ('MAC_ROMAN', MacRoman), ('WIN_ANSI', winansi())]:
        enc = [e if e else '.notdef' for e in list(enc)[:256]]
        enc += ['.notdef'] * (256 - len(enc))
        lines.append(f'pub static {name}: [&str; 256] = [')
        for i in range(0, 256, 8):
            lines.append('    ' + ', '.join(f'"{e}"' for e in enc[i:i + 8]) + ',')
        lines.append('];')
    open('crates/oc-pdf/src/tables.rs', 'w').write('\n'.join(lines) + '\n')
main()
