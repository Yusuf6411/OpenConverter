#!/usr/bin/env python3
"""Generate crates/oc-av1/src/cdf.rs (the Cdfs struct) from the default CDF statics in tables.rs.

Usage: gen_av1_cdf.py crates/oc-av1/src/tables.rs crates/oc-av1/src/cdf.rs
"""
import re
import sys

src = open(sys.argv[1]).read()
types = {}
for m in re.finditer(r"pub static (DEFAULT_[A-Z0-9_]*_CDF): ([^=]*) =", src):
    types[m.group(1)] = m.group(2).strip()


def dims(t):
    d = []
    while t.startswith("["):
        inner = t[1:-1]
        i = inner.rindex(";")
        d.append(int(inner[i + 1:]))
        t = inner[:i].strip()
    return d  # t must be u16 at the end


def field_name(n):
    return n[len("DEFAULT_"):-len("_CDF")].lower()


COEFF = {"txb_skip", "eob_pt_16", "eob_pt_32", "eob_pt_64", "eob_pt_128", "eob_pt_256", "eob_pt_512",
         "eob_pt_1024", "eob_extra", "dc_sign", "coeff_base_eob", "coeff_base", "coeff_br"}
# Default has no per-component dimension: replicate [ctx][comp]
MV_CTX_COMP = {"mv_class0_bit", "mv_class0_hp", "mv_sign", "mv_bit", "mv_hp"}
MV_CTX = {"mv_joint", "mv_class", "mv_fr", "mv_class0_fr"}

fields = []  # (name, dims list)
inits = []
for n, t in types.items():
    f = field_name(n)
    d = dims(t)
    if f in COEFF:
        d = d[1:]
    if f in MV_CTX_COMP:
        d = [2, 2] + d
    elif f in MV_CTX:
        d = [2] + d
    fields.append((f, d, n))
fields.append(("delta_lf_multi", [4] + dims(types["DEFAULT_DELTA_LF_CDF"]), None))


def ty(d):
    t = "u16"
    for n in reversed(d):
        t = f"[{t}; {n}]"
    return t


out = []
out.append("// Generated by tools/gen_av1_cdf.py. Do not edit.\n")
out.append("use crate::tables::*;\n\n")
out.append("#[derive(Clone)]\npub struct Cdfs {\n")
for f, d, n in fields:
    out.append(f"    pub {f}: {ty(d)},\n")
out.append("}\n\nimpl Cdfs {\n")
out.append("    /// init_non_coeff_cdfs plus init_coeff_cdfs for the given base_q_idx.\n")
out.append("    pub fn new(base_q_idx: i32) -> Cdfs {\n")
out.append("        let q = if base_q_idx <= 20 { 0 } else if base_q_idx <= 60 { 1 } else if base_q_idx <= 120 { 2 } else { 3 };\n")
out.append("        Cdfs {\n")
for f, d, n in fields:
    if n is None:
        out.append(f"            {f}: [DEFAULT_DELTA_LF_CDF; 4],\n")
    elif f in COEFF:
        out.append(f"            {f}: {n}[q],\n")
    elif f in MV_CTX_COMP:
        out.append(f"            {f}: [[{n}; 2]; 2],\n")
    elif f in MV_CTX:
        out.append(f"            {f}: [{n}; 2],\n")
    else:
        out.append(f"            {f}: {n},\n")
out.append("        }\n    }\n\n")
out.append("    /// Zero the adaptation counter (the last entry) of every CDF.\n")
out.append("    pub fn clear_counts(&mut self) {\n")
for f, d, n in fields:
    var = f"self.{f}"
    depth = len(d) - 1  # arrays above the innermost cdf
    cur = var
    ind = "        "
    for i in range(depth):
        out.append(f"{ind}for a{i} in {cur}.iter_mut() {{\n")
        cur = f"a{i}"
        ind += "    "
    out.append(f"{ind}{cur}[{d[-1] - 1}] = 0;\n")
    for i in range(depth):
        ind = ind[:-4]
        out.append(f"{ind}}}\n")
out.append("    }\n}\n")
open(sys.argv[2], "w").write("".join(out))
print("fields:", len(fields))
