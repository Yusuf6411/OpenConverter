#!/usr/bin/env python3
"""Write crates/oc-document/src/entities.rs from Python's copy of the WHATWG entity list."""
import html.entities as h, sys

def lit(s):
    return '"' + "".join(c if (c.isprintable() and c not in '"\\') else "\\u{%x}" % ord(c) for c in s) + '"'

full = sorted((k[:-1], v) for k, v in h.html5.items() if k.endswith(";"))
legacy = sorted(k for k in h.html5 if not k.endswith(";"))
out = ["//! HTML named character references (generated by tools/gen_entities.py; do not edit).", "",
       "/// Names without the trailing semicolon, sorted.", "pub static NAMED: &[(&str, &str)] = &["]
out += ["    (%s, %s)," % (lit(k), lit(v)) for k, v in full]
out += ["];", "", "/// Names HTML accepts without a trailing semicolon, sorted.", "pub static LEGACY: &[&str] = &["]
out += ["    %s," % lit(k) for k in legacy]
out += ["];", ""]
open("crates/oc-document/src/entities.rs", "w").write("\n".join(out))
