#!/usr/bin/env python3
"""Extracts the Brotli static dictionary (RFC 7932 Appendix A) and the word transforms
(Appendix B) from docs/specs/rfc7932.txt, checks both against the CRCs the RFC states, and
writes crates/oc-compress/src/brotli_dict.bin and brotli_transforms.rs."""
import re, zlib, ast, sys
L = open('docs/specs/rfc7932.txt', encoding='utf-8').read().split('\n')
a = next(k for k, l in enumerate(L) if l.startswith('Appendix A.  Static'))
b = next(k for k, l in enumerate(L) if l.startswith('Appendix B.'))
c = next(k for k, l in enumerate(L) if l.startswith('Appendix C.'))
h = ''.join(m.group(1) for l in L[a:b] if (m := re.fullmatch(r'\s+([0-9a-f]{64})', l)))
d = bytes.fromhex(h)
assert len(d) == 122784 and zlib.crc32(d) == 0x5136CB04
open('crates/oc-compress/src/brotli_dict.bin', 'wb').write(d)
KINDS = {'Identity': 0, 'FermentFirst': 1, 'FermentAll': 2}
for i in range(1, 10):
    KINDS[f'OmitFirst{i}'] = 2 + i
    KINDS[f'OmitLast{i}'] = 11 + i
rows, blob = [], b''
for l in L[b:c]:
    m = re.fullmatch(r'\s+(\d+)\s+("(?:[^"\\]|\\.)*")\s+(\w+)\s+("(?:[^"\\]|\\.)*")\s*', l)
    if not m:
        continue
    pre = ast.literal_eval(m.group(2)).encode('latin-1')
    suf = ast.literal_eval(m.group(4)).encode('latin-1')
    k = KINDS[m.group(3)]
    assert int(m.group(1)) == len(rows)
    rows.append((pre, k, suf))
    blob += pre + b'\0' + bytes([k]) + suf + b'\0'
assert len(rows) == 121 and len(blob) == 648 and zlib.crc32(blob) == 0x3D965F81, (len(rows), len(blob), hex(zlib.crc32(blob)))
def lit(x): return 'b"' + ''.join(f'\\x{c:02x}' for c in x) + '"'
with open('crates/oc-compress/src/brotli_transforms.rs', 'w') as f:
    f.write('// Generated by tools/gen_brotli_tables.py from RFC 7932 Appendix B. Do not edit.\n')
    f.write('// (prefix, kind, suffix): kind 0 identity, 1 ferment first, 2 ferment all,\n// 3..=11 omit first 1..=9, 12..=20 omit last 1..=9.\n')
    f.write('pub(crate) const TRANSFORMS: [(&[u8], u8, &[u8]); 121] = [\n')
    for p, k, s in rows:
        f.write(f'    ({lit(p)}, {k}, {lit(s)}),\n')
    f.write('];\n')
# Context lookup tables (Section 7.1).
t0 = next(k for k, l in enumerate(L) if l.strip() == 'Lut0 :=')
def table(name, crc):
    k = next(i for i, l in enumerate(L) if l.strip() == name + ' :=')
    nums = []
    while len(nums) < 256:
        k += 1
        nums += [int(x) for x in re.findall(r'\d+', L[k]) if L[k].strip() and not L[k].startswith(('RFC', 'Alaku'))]
    nums = nums[:256]
    assert zlib.crc32(bytes(nums)) == crc, name
    return nums
luts = [table('Lut0', 0x8E91EFB7), table('Lut1', 0xD01A32F4), table('Lut2', 0x0DD7A0D6)]
with open('crates/oc-compress/src/brotli_transforms.rs', 'a') as f:
    for n, t in enumerate(luts):
        f.write(f'pub(crate) const LUT{n}: [u8; 256] = {t};\n')
print('ok', len(rows))
